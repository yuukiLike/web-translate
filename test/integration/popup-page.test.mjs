import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

import {
	createPopupPageHarness,
	createPopupState,
	waitFor,
} from "../helpers/popup-page-harness.mjs";

const extensionUrl = new URL("../../chrome-extension/", import.meta.url);

function readExtensionFile(path) {
	return readFile(new URL(path, extensionUrl), "utf8");
}

// 验证 Manifest 指向本地 Popup，页面不包含内联或远程代码，生成资产满足 MV3 CSP。
test("Popup 仅加载本地预编译资产", async () => {
	const [manifestSource, html, script, styles] = await Promise.all([
		readExtensionFile("manifest.json"),
		readExtensionFile("popup/index.html"),
		readExtensionFile("popup/popup.js"),
		readExtensionFile("popup/popup.css"),
	]);
	const manifest = JSON.parse(manifestSource);
	const scriptSources = [...html.matchAll(/<script\s+src="([^"]+)"><\/script>/gu)].map(
		(match) => match[1],
	);
	const styleSources = [...html.matchAll(/<link\s+rel="stylesheet"\s+href="([^"]+)"\s*\/?>/gu)].map(
		(match) => match[1],
	);

	assert.equal(manifest.action.default_popup, "popup/index.html");
	assert.deepEqual(scriptSources, ["popup.js"]);
	assert.deepEqual(styleSources, ["popup.css"]);
	assert.ok([...scriptSources, ...styleSources].every((source) => !/^(?:https?:)?\/\//u.test(source)));
	assert.doesNotMatch(html, /<script(?!\s+src=)[^>]*>/u);
	assert.doesNotMatch(html, /\son[a-z]+\s*=|<style[\s>]/iu);
	assert.match(html, /<h1 class="brand-title">一键双语<\/h1>/u);
	assert.match(html, /<select id="source-language">/u);
	assert.match(html, /<select id="target-language">/u);
	assert.doesNotMatch(html, />当前网页<|把译文排在原文下方|译文紧随原文/u);
	assert.match(html, /aria-label="翻译 \/ 恢复当前网页"/u);
	assert.match(script, /^\/\/ Generated by scripts\/build-popup\.mjs/u);
	assert.match(styles, /^\/\* Generated by scripts\/build-popup\.mjs/u);
	assert.doesNotMatch(script, /\beval\s*\(|\bnew\s+Function\s*\(|\bimport\s*\(/u);
});

// 验证后台状态返回前主操作保持加载态，返回后再一次性填充服务信息并允许点击。
test("Popup 从加载态进入就绪态", async () => {
	const state = Promise.withResolvers();
	const page = await createPopupPageHarness({ getPopupState: () => state.promise });
	try {
		const toggle = page.document.querySelector("#toggle-translation");
		assert.equal(toggle.disabled, true);
		assert.match(page.document.querySelector("#popup-status").textContent, /正在连接/u);

		state.resolve(createPopupState());
		await waitFor(() => !toggle.disabled, "Popup 未离开加载态");
		assert.equal(page.document.querySelector("#extension-version").textContent, "v0.4.0");
		assert.equal(page.document.querySelector("#current-provider").textContent, "DeepSeek");
		assert.equal(page.document.querySelector("#current-model").textContent, "deepseek-v4-flash");
		assert.equal(page.document.querySelector("#source-language").value, "auto");
		assert.equal(page.document.querySelector("#target-language").value, "zh");
		assert.equal(page.document.querySelector("#language-fields").disabled, false);
		assert.equal(page.document.querySelector("#popup-status").dataset.tone, "ready");
		assert.match(toggle.textContent, /翻译 \/ 恢复/u);
		assert.equal(toggle.getAttribute("aria-label"), "翻译 / 恢复当前网页");
	} finally {
		state.resolve(createPopupState());
		page.cleanup();
	}
});

