// 验证初始状态读取失败时保持安全禁用，并把后台错误显示在可访问状态区域。
test("Popup 安全处理初始加载错误", async () => {
	const page = await createPopupPageHarness({
		getPopupState: async () => ({ ok: false, error: "无法读取当前页面" }),
	});
	try {
		await waitFor(
			() => page.document.querySelector("#popup-status").textContent.includes("无法读取"),
			"Popup 未展示初始加载错误",
		);
		assert.equal(page.document.querySelector("#toggle-translation").disabled, true);
		assert.equal(page.document.querySelector("#popup-status").dataset.error, "true");
		assert.equal(page.document.querySelector("#current-provider").textContent, "后台暂时不可用");
		assert.equal(page.document.querySelector("#current-model").textContent, "请稍后重试");
		assert.equal(page.document.querySelector("#language-fields").disabled, true);
		assert.doesNotMatch(page.document.body.textContent, /正在读取/u);
	} finally {
		page.cleanup();
	}
});

// 验证旧后台不认识 Popup 新协议时结束加载占位，并提供可以自助恢复的重新载入入口。
test("Popup 将后台协议错配转换为可恢复状态", async () => {
	const state = Promise.withResolvers();
	const page = await createPopupPageHarness({
		getPopupState: () => state.promise,
	});
	try {
		const toggle = page.document.querySelector("#toggle-translation");
		assert.equal(page.document.querySelector("#current-provider").textContent, "正在读取…");
		assert.equal(toggle.disabled, true);

		state.resolve({ ok: false, error: "未知消息类型" });
		await waitFor(
			() => page.document.querySelector("#current-provider").textContent.includes("后台"),
			"Popup 未结束协议错配加载态",
		);

		assert.equal(page.document.querySelector("#current-provider").textContent, "后台版本未同步");
		assert.equal(page.document.querySelector("#current-model").textContent, "重新载入扩展后再试");
		assert.equal(page.document.querySelector("#language-fields").disabled, true);
		assert.match(page.document.querySelector("#popup-status").textContent, /重新载入/u);
		assert.doesNotMatch(page.document.body.textContent, /正在读取/u);
		assert.equal(toggle.disabled, false);
		assert.match(toggle.textContent, /重新载入扩展/u);
		assert.equal(toggle.getAttribute("aria-label"), "重新载入扩展");

		toggle.click();
		toggle.click();
		await waitFor(() => page.reloadCount === 1, "Popup 未重新载入扩展");
		assert.equal(toggle.disabled, true);
		assert.equal(toggle.getAttribute("aria-label"), "正在重新载入扩展");
		assert.equal(page.closeCount, 1);
		assert.deepEqual(page.calls.map(({ type }) => type), ["GET_POPUP_STATE"]);
	} finally {
		state.resolve({ ok: false, error: "未知消息类型" });
		page.cleanup();
	}
});

// 验证 Chrome 拒绝重新载入时保留错误提示并恢复按钮，用户仍能再次尝试。
test("Popup 从扩展重新载入失败中恢复", async () => {
	const page = await createPopupPageHarness({
		getPopupState: async () => ({ ok: false, error: "未知消息类型" }),
		reloadError: new Error("模拟重新载入失败"),
	});
	try {
		const toggle = page.document.querySelector("#toggle-translation");
		await waitFor(() => !toggle.disabled, "Popup 未进入协议恢复状态");

		toggle.click();
		await waitFor(
			() => page.document.querySelector("#popup-status").textContent.includes("模拟"),
			"Popup 未显示重新载入错误",
		);
		assert.equal(page.reloadCount, 1);
		assert.equal(page.closeCount, 0);
		assert.equal(toggle.disabled, false);
		assert.match(toggle.textContent, /重新载入扩展/u);
		assert.equal(toggle.getAttribute("aria-label"), "重新载入扩展");
	} finally {
		page.cleanup();
	}
});

