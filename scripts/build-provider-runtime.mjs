import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

import { loadValidatedConfiguration } from "./validate-provider-config.mjs";

const applicationRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputDirectory = resolve(applicationRoot, "chrome-extension/generated");
const runtimeOutputPath = resolve(outputDirectory, "provider-runtime.js");
const catalogOutputPath = resolve(outputDirectory, "provider-catalog.js");
const checkOnly = process.argv.slice(2).includes("--check");

if (process.argv.slice(2).some((argument) => argument !== "--check")) {
	throw new Error("Usage: node scripts/build-provider-runtime.mjs [--check]");
}

function createGeneratedCatalog(catalog, allowlist) {
	const catalogProviders = new Map(catalog.providers.map((provider) => [provider.id, provider]));
	return {
		schemaVersion: catalog.schemaVersion,
		source: catalog.source,
		defaultProviderId: allowlist.defaultProviderId,
		providers: Object.fromEntries(
			allowlist.providers.map((allowedProvider) => {
				const catalogProvider = catalogProviders.get(allowedProvider.id);
				return [
					allowedProvider.id,
					{
						id: allowedProvider.id,
						name: catalogProvider.name,
						sdkPackage: allowedProvider.sdkPackage,
						apiBaseURL: allowedProvider.apiBaseURL,
						defaultModelId: allowedProvider.defaultModelId,
						models: Object.fromEntries(
							catalogProvider.models.map((model) => [model.id, model]),
						),
					},
				];
			}),
		),
	};
}

function renderCatalogScript(catalog) {
	return `// Generated by scripts/build-provider-runtime.mjs. Do not edit.\n(() => {\n\t"use strict";\n\n\tfunction deepFreeze(value) {\n\t\tfor (const nested of Object.values(value)) {\n\t\t\tif (nested && typeof nested === "object" && !Object.isFrozen(nested)) {\n\t\t\t\tdeepFreeze(nested);\n\t\t\t}\n\t\t}\n\t\treturn Object.freeze(value);\n\t}\n\n\tglobalThis.BilingualTranslatorProviderCatalog = deepFreeze(${JSON.stringify(catalog, null, "\t")});\n})();\n`;
}

const { catalog, allowlist } = await loadValidatedConfiguration();
const bundle = await build({
	absWorkingDir: applicationRoot,
	bundle: true,
	entryPoints: ["src/provider-runtime.js"],
	format: "iife",
	legalComments: "eof",
	logLevel: "warning",
	minify: true,
	outfile: runtimeOutputPath,
	platform: "browser",
	target: "chrome140",
	banner: {
		js: "globalThis.__zod_globalConfig = Object.assign(globalThis.__zod_globalConfig ?? {}, { jitless: true });",
	},
	write: false,
});
const runtimeOutput = bundle.outputFiles.find((file) => file.path === runtimeOutputPath);
if (!runtimeOutput) {
	throw new Error("esbuild did not produce the provider runtime bundle");
}
const runtimeContents = Buffer.from(runtimeOutput.contents)
	.toString("utf8")
	.replace(/^[\t ]+$/gmu, "");

const catalogContents = renderCatalogScript(createGeneratedCatalog(catalog, allowlist));
if (checkOnly) {
	let existingCatalog;
	let existingRuntime;
	try {
		[existingCatalog, existingRuntime] = await Promise.all([
			readFile(catalogOutputPath),
			readFile(runtimeOutputPath),
		]);
	} catch {
		throw new Error("Generated Provider files are missing. Run npm run build:provider-runtime.");
	}
	if (
		!existingCatalog.equals(Buffer.from(catalogContents)) ||
		!existingRuntime.equals(Buffer.from(runtimeContents))
	) {
		throw new Error("Generated Provider files are stale. Run npm run build:provider-runtime.");
	}
	console.log("Generated Provider files are up to date.");
} else {
	await mkdir(outputDirectory, { recursive: true });
	await Promise.all([
		writeFile(catalogOutputPath, catalogContents, "utf8"),
		writeFile(runtimeOutputPath, runtimeContents, "utf8"),
	]);
	console.log(
		"Generated chrome-extension/generated/provider-catalog.js and chrome-extension/generated/provider-runtime.js.",
	);
}
