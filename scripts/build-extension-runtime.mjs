import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

import {
	assertNoExternalImports,
	collectBundleOutputs,
	parseBuildArguments,
	writeOrCheckOutputs,
} from "./build-outputs.mjs";
import { loadValidatedConfiguration } from "./validate-provider-config.mjs";

const applicationRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputDirectory = resolve(applicationRoot, "chrome-extension/generated");
const { checkOnly } = parseBuildArguments("build-extension-runtime.mjs");
const generatedNotice = "// Generated by scripts/build-extension-runtime.mjs. Do not edit.";

function createGeneratedCatalog(catalog, allowlist) {
	const catalogProviders = new Map(catalog.providers.map((provider) => [provider.id, provider]));
	return {
		schemaVersion: catalog.schemaVersion,
		source: catalog.source,
		defaultProviderId: allowlist.defaultProviderId,
		providers: Object.fromEntries(
			allowlist.providers.map((allowedProvider) => {
				const catalogProvider = catalogProviders.get(allowedProvider.id);
				return [
					allowedProvider.id,
					{
						id: allowedProvider.id,
						name: catalogProvider.name,
						sdkPackage: allowedProvider.sdkPackage,
						apiBaseURL: allowedProvider.apiBaseURL,
						defaultModelId: allowedProvider.defaultModelId,
						models: Object.fromEntries(
							catalogProvider.models.map((model) => [model.id, model]),
						),
					},
				];
			}),
		),
	};
}

function renderCatalogScript(catalog) {
	return `${generatedNotice}\n(() => {\n\t"use strict";\n\n\tfunction deepFreeze(value) {\n\t\tfor (const nested of Object.values(value)) {\n\t\t\tif (nested && typeof nested === "object" && !Object.isFrozen(nested)) {\n\t\t\t\tdeepFreeze(nested);\n\t\t\t}\n\t\t}\n\t\treturn Object.freeze(value);\n\t}\n\n\tglobalThis.BilingualTranslatorProviderCatalog = deepFreeze(${JSON.stringify(catalog, null, "\t")});\n})();\n`;
}

async function bundleRuntime({ entryPoint, outputName, banner = generatedNotice }) {
	const outputPath = resolve(outputDirectory, outputName);
	const bundle = await build({
		absWorkingDir: applicationRoot,
		banner: { js: banner },
		bundle: true,
		entryPoints: [entryPoint],
		format: "iife",
		legalComments: "eof",
		logLevel: "warning",
		metafile: true,
		minify: true,
		outfile: outputPath,
		platform: "browser",
		target: "chrome140",
		write: false,
	});
	assertNoExternalImports(bundle.metafile, "Runtime");
	const outputs = collectBundleOutputs(bundle.outputFiles, [outputPath], "runtime");
	const normalized = outputs.get(outputPath)
		.toString("utf8")
		.replace(/^[\t ]+$/gmu, "");
	return Buffer.from(normalized);
}

const { catalog, allowlist } = await loadValidatedConfiguration();
const providerBanner = `${generatedNotice}\nglobalThis.__zod_globalConfig = Object.assign(globalThis.__zod_globalConfig ?? {}, { jitless: true });`;
const outputs = new Map([
	[
		resolve(outputDirectory, "provider-catalog.js"),
		Buffer.from(renderCatalogScript(createGeneratedCatalog(catalog, allowlist))),
	],
	[
		resolve(outputDirectory, "provider-runtime.js"),
		await bundleRuntime({
			entryPoint: "src/provider-runtime.js",
			outputName: "provider-runtime.js",
			banner: providerBanner,
		}),
	],
	[
		resolve(outputDirectory, "core.js"),
		await bundleRuntime({ entryPoint: "src/core/main.js", outputName: "core.js" }),
	],
	[
		resolve(outputDirectory, "content-script.js"),
		await bundleRuntime({
			entryPoint: "src/content/main.js",
			outputName: "content-script.js",
		}),
	],
]);

await writeOrCheckOutputs(outputs, { checkOnly, buildCommand: "npm run build:runtime" });

console.log(
	checkOnly
		? "Generated extension runtime files are up to date."
		: `Generated ${[...outputs.keys()].map((path) => basename(path)).join(", ")}.`,
);
